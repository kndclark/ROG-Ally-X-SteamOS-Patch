def create_device():
    print("Creating virtual ROG Ally X...")
    fd = os.open('/dev/uhid', os.O_RDWR | os.O_NONBLOCK)
    
    # uhid_create2_req struct:
    # __u32 type;
    # __u8 name[128];
    # __u8 phys[64];
    # __u8 uniq[64];
    # __u16 rd_size;
    # __u16 bus;
    # __u32 vendor;
    # __u32 product;
    # __u32 version;
    # __u32 country;
    # __u8 rd_data[4096];
    
    name = b'Virtual ROG Ally X\0' + b'\0' * (128 - 19)
    phys = b'virt/uhid\0' + b'\0' * (64 - 10)
    uniq = b'\0' * 64
    rd_size = len(rd)
    rd_data = rd + b'\0' * (4096 - rd_size)
    
    req = struct.pack('<I 128s 64s 64s H H I I I I 4096s',
                      UHID_CREATE2, name, phys, uniq, rd_size, BUS_USB,
                      VENDOR_ID, PRODUCT_ID, 0, 0, rd_data)
    
    os.write(fd, req)
    return fd

def destroy_device(fd):
    print("Destroying virtual ROG Ally X...")
    req = struct.pack('<I', UHID_DESTROY)
    os.write(fd, req)
    os.close(fd)

def run():
    fd = create_device()
    print("Virtual device created. Monitoring for kernel requests for 30 seconds...")
    try:
        end_time = time.time() + 30
        while time.time() < end_time:
            # We would normally read from fd to handle UHID_OUTPUT and UHID_GET_REPORT here
            time.sleep(1)
    except KeyboardInterrupt:
        pass
    finally:
        destroy_device(fd)

if __name__ == '__main__':
    run()
